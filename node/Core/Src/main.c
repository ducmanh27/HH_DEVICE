/* USER CODE BEGIN 4 */
static void monitor_energy(void* parameters)
{
	for (;;)
	{
		if (xSemaphoreTake(xSensorMutex, portMAX_DELAY)) {
			if (PZEM004T_ReadData(&energySensor) == PZEM004T_SUCESS){
				sensorData.current = energySensor.data.current;
				sensorData.voltage = energySensor.data.voltage;
				sensorData.power = energySensor.data.power;
				sensorData.energy = energySensor.data.energy;
				sensorData.pf = energySensor.data.pf;
				sensorData.frequency = energySensor.data.frequency;
			}
			else
			{
				sensorData.current = 0.0;
				sensorData.voltage = 0.0;
				sensorData.power = 0.0;
				sensorData.energy = 0.0;
				sensorData.pf = 0.0;
				sensorData.frequency = 0.0;
			}
			xSemaphoreGive(xSensorMutex);
		}
		xSemaphoreGive(xPZEMUpdated);
		vTaskDelay(pdMS_TO_TICKS(1000));
	}
}
static void monitor_dust(void* parameters)
{
	for (;;)
	{
		if (xSemaphoreTake(xSensorMutex, portMAX_DELAY)) {
			sensorData.temperature = SHT2x_GetTemperature(1);
			sensorData.humidity = SHT2x_GetRelativeHumidity(1);
			sensorData.dust_density = fake_dust_density++;
			xSemaphoreGive(xSensorMutex);
		}
		xSemaphoreGive(xDustUpdated);
		vTaskDelay(pdMS_TO_TICKS(1000));
	}
}
