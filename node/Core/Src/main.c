/**
 * @brief Convert RTC date and time (from HAL RTC) to Unix timestamp.
 *
 * This function converts the date and time values retrieved from the STM32 HAL RTC
 * peripheral (in RTC_DateTypeDef and RTC_TimeTypeDef structures) into a Unix timestamp.
 * The Unix timestamp represents the number of seconds elapsed since
 * January 1, 1970 (UTC).
 *
 * Note:
 * - HAL RTC Year field counts years from 2000, while struct tm counts from 1900.
 * - tm_mon expects months in range 0-11, but HAL RTC uses 1-12.
 * - mktime() converts the time as local time; if RTC time is UTC, consider implementing
 *   timegm() or equivalent to avoid timezone offset.
 *
 * @param date Pointer to RTC_DateTypeDef structure containing date information.
 * @param time Pointer to RTC_TimeTypeDef structure containing time information.
 * @return time_t Unix timestamp corresponding to the input date and time.
 */
static uint32_t getCurrentTime()
{
	RTC_TimeTypeDef time = {0};
	RTC_DateTypeDef date = {0};
    HAL_RTC_GetTime(&hrtc, &time, RTC_FORMAT_BIN);
    HAL_RTC_GetDate(&hrtc, &date, RTC_FORMAT_BIN);
    struct tm t;

    // Populate struct tm fields from HAL RTC date and time
    t.tm_year = (date.Year) + 100;  // Years since 1900, HAL counts from 2000, so add 100
    t.tm_mon  = date.Month - 1;     // Months since January [0-11], HAL months [1-12]
    t.tm_mday = date.Date;          // Day of the month [1-31]
    t.tm_hour = time.Hours;         // Hours [0-23]
    t.tm_min  = time.Minutes;       // Minutes [0-59]
    t.tm_sec  = time.Seconds;       // Seconds [0-59]
    t.tm_isdst = 0;                  // Daylight Saving Time flag (0 = no DST)

    // Convert struct tm to time_t (Unix timestamp)
    // mktime assumes input is local time.
    // mktime(&t);
    return (uint32_t)(mktime(&t));

}
